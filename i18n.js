// Also handle placeholder translations
function applyPlaceholders(lang) {
  const t = translations[lang];
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (t[key]) el.placeholder = t[key];
  });
}

// Patch applyLanguage to also handle placeholders and select options
const _origApply = applyLanguage;
// Override
window.applyLanguage = function(lang) {
  const t = translations[lang];
  if (!t) return;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key] !== undefined) el.innerHTML = t[key];
  });
  applyPlaceholders(lang);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.classList.toggle('active', btn.getAttribute('data-lang') === lang);
  });
  document.documentElement.lang = lang;
  localStorage.setItem('mervil_lang', lang);
};

// Re-init with patched function on DOM ready
document.addEventListener('DOMContentLoaded', () => {
  const savedLang = localStorage.getItem('mervil_lang') || 'en';
  window.applyLanguage(savedLang);
  document.querySelectorAll('.lang-btn').forEach(btn => {
    btn.addEventListener('click', () => window.applyLanguage(btn.getAttribute('data-lang')));
  });
});
